import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outputPath = resolve(root, "src/design/identity/generated-vectors.ts");

const sources = {
  registerMicro: "src/design/identity/masters/register-micro.svg",
  registerCompact: "src/design/identity/masters/register-compact.svg",
  registerStandard: "src/design/identity/masters/register-standard.svg",
  wordmark: "src/design/identity/masters/sunday-ledger-wordmark.svg",
  horizontal: "src/design/identity/lockups/horizontal.svg",
  compact: "src/design/identity/lockups/compact.svg",
};

function readVector(relativePath) {
  const source = readFileSync(resolve(root, relativePath), "utf8");
  const viewBox = source.match(/\bviewBox="([^"]+)"/)?.[1];
  const inner = source
    .replace(/^[\s\S]*?<svg\b[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/\s*<title>[\s\S]*?<\/title>/g, "")
    .replace(/\s*<desc>[\s\S]*?<\/desc>/g, "")
    .replace(/\s*<metadata>[\s\S]*?<\/metadata>/g, "")
    .trim();

  if (!viewBox || !inner) {
    throw new Error(`Unable to extract vector geometry from ${relativePath}`);
  }

  return { source: relativePath, viewBox, inner };
}

const vectors = Object.fromEntries(
  Object.entries(sources).map(([name, relativePath]) => [
    name,
    readVector(relativePath),
  ]),
);

const generated =
  `// Generated by scripts/generate-identity-vectors.mjs. Do not edit.\n` +
  `export const IDENTITY_VECTORS = ${JSON.stringify(vectors, null, 2)} as const;\n`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) {
    throw new Error(
      "Generated identity vectors are stale. Run npm run identity:generate.",
    );
  }
} else {
  writeFileSync(outputPath, generated);
}
